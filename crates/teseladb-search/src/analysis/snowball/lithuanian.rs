static BUILT: OnceLock<Vec<Step>> = OnceLock::new();

/// Whether `c` is a vowel of the regions.
fn vowel(c: char) -> bool {
    matches!(c, 'a' | 'e' | 'i' | 'y' | 'o' | 'u' | 'ą' | 'ę' | 'į' | 'ų' | 'ė' | 'ū')
}

/// The stem of `word`.
pub fn stem(word: &str) -> String {
    let c: Vec<char> = word.chars().collect();
    let from = usize::from(c.len() > 6 && c.first() == Some(&'a'));
    let r1 = region(&c, from, vowel);
    let r2 = region(&c, r1, vowel);
    let mut s: Vec<char> =
        run_marked(c, BUILT.get_or_init(|| build(&STEPS)), [0, r1, r2]).chars().collect();
    match s.as_slice() {
        [.., 'č'] => {
            s.pop();
            s.push('t');
        }
        [.., 'd', 'ž'] => {
            s.pop();
        }
        _ => {}
    }
    if s.ends_with(&['g', 'd']) {
        s.pop();
    }
    s.into_iter().collect()
}
