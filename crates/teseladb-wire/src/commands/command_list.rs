//! The commands of `listCommands` with the fields each one has (006 FR-033). Measured on
//! 04-11-2026: the commands a `refrouter` 9.0.4 lists as it lists them; `applyOps`, `autoCompact`,
//! `shardingState` and the `replSet*` commands, which a `refrouter` does not have, as a `refnode`
//! 9.0.4 lists them, and `logApplicationMessage` as RefDb Enterprise 9.0.4 does;
//! `configureFailPoint` as a `refrouter` 9.0.4 with `enableTestCommands` lists it. The API key
//! commands are TeselaDB's own (019 FR-016). In byte order of their names, as a `refrouter` lists
//! them; the dispatch answers each of them and no other (test `list_commands_names_what_the_dispatch_takes`).

/// One command of `listCommands`.
pub(super) struct CommandInfo {
    pub name: &'static str,
    pub help: &'static str,
    pub requires_auth: bool,
    pub requires_authz_checks: bool,
    pub secondary_ok: bool,
    pub admin_only: bool,
    /// `secondaryOverrideOk: true`, which only some commands have.
    pub secondary_override_ok: bool,
    /// `apiVersions: ["1"]`; every `deprecatedApiVersions` is empty.
    pub api_v1: bool,
}

/// `[requiresAuth, requiresAuthzChecks, secondaryOk, adminOnly, secondaryOverrideOk, apiVersions 1]`.
const fn c(name: &'static str, help: &'static str, f: [bool; 6]) -> CommandInfo {
    let [
        requires_auth,
        requires_authz_checks,
        secondary_ok,
        admin_only,
        secondary_override_ok,
        api_v1,
    ] = f;
    CommandInfo {
        name,
        help,
        requires_auth,
        requires_authz_checks,
        secondary_ok,
        admin_only,
        secondary_override_ok,
        api_v1,
    }
}

/// Whether command `name` is in API Version 1 (`apiVersions: ["1"]` in `listCommands`).
pub(crate) fn in_api_v1(name: &str) -> bool {
    COMMANDS.iter().any(|c| c.name == name && c.api_v1)
}

