#[test]
fn edges_behave_as_the_reference() {
    let wrong: Vec<String> = CASES
        .iter()
        .filter_map(|&(pattern, options, subject, want)| {
            let got = match Regex::new(pattern, options) {
                Ok(re) => match re.is_match(subject) {
                    Ok(m) => Ok(m),
                    Err(e) => Err(e.message),
                },
                Err(e) => Err(e.message),
            };
            let same = match (&got, want) {
                (Ok(g), Ok(w)) => *g == w,
                (Err(g), Err(w)) => g.strip_prefix("Regular expression is invalid: ") == Some(w),
                _ => false,
            };
            (!same).then(|| format!("/{pattern}/{options} on {subject:?}: {got:?}, not {want:?}"))
        })
        .collect();
    assert!(wrong.is_empty(), "{} differ:\n{}", wrong.len(), wrong.join("\n"));
}
