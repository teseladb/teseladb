#!/usr/bin/env python3
"""Writes crates/teseladb-auth/src/stringprep_tables.rs from the appendix tables of RFC 3454
(https://www.rfc-editor.org/rfc/rfc3454.txt) that SASLprep (RFC 4013) uses.
   python3 -I scripts/gen-stringprep-tables.py <rfc3454.txt> > crates/teseladb-auth/src/stringprep_tables.rs
"""
import hashlib
import re
import sys

TABLES = ["A.1", "B.1", "C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9", "D.1", "D.2"]

raw = open(sys.argv[1], "rb").read()
text = raw.decode("ascii")
out = [
    "//! Tables of RFC 3454, appendices A to D, as SASLprep (RFC 4013) uses them: ranges of code",
    "//! points, inclusive and sorted. Generated by `scripts/gen-stringprep-tables.py` from",
    "//! https://www.rfc-editor.org/rfc/rfc3454.txt (SHA-256 %s); do not edit." % hashlib.sha256(raw).hexdigest(),
    "",
]
for name in TABLES:
    m = re.search(r"----- Start Table %s -----\n(.*?)----- End Table %s -----" % (re.escape(name), re.escape(name)), text, re.S)
    ranges = []
    for line in m.group(1).split("\n"):
        line = line.strip()
        if not line or line.startswith("RFC 3454") or line.startswith("Hoffman"):
            continue
        cp = line.split(";")[0].strip()
        if not re.fullmatch(r"[0-9A-F]+(-[0-9A-F]+)?", cp):
            continue
        a, _, b = cp.partition("-")
        ranges.append((int(a, 16), int(b or a, 16)))
    ranges.sort()
    const = "T_" + name.replace(".", "_")
    out.append("/// Table %s." % name)
    out.append("pub const %s: &[(u32, u32)] = &[" % const)
    for a, b in ranges:
        out.append("    (0x%04X, 0x%04X)," % (a, b))
    out.append("];")
    out.append("")
sys.stdout.write("\n".join(out))
