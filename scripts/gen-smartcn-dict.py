#!/usr/bin/env python3
"""Writes crates/teseladb-search/data/smartcn-words.txt for the smartcn search analyzer (011 T009,
D-109) from the ICU 74.2 dictionary cjdict.txt and the Unihan 15.1 variants, both fetched with their
SHA-256 by scripts/fetch-pinned.sh (scripts/smartcn.sha256, scripts/unihan.sha256).

   python3 -I scripts/gen-smartcn-dict.py

The dictionary of the reference smartcn analyzer exists only inside the reference analyzers, so the
analyzer cuts Chinese with the ICU dictionary instead (divergence recorded for 011). smartcn knows simplified Chinese words
only: a word of two or more characters is kept when none of its characters is a traditional form
(a character whose Unihan kSimplifiedVariant differs from it). Each line is a word, a tab and its
ICU cost; the header keeps the notices of cjdict.txt.
"""
import io
import os
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CJDICT = ROOT + "/.tools/smartcn/cjdict.txt"
UNIHAN = ROOT + "/.tools/unicode/unihan-15.1.0/Unihan.zip"
OUT = ROOT + "/crates/teseladb-search/data/smartcn-words.txt"

traditional = set()
with zipfile.ZipFile(UNIHAN) as z:
    for line in io.TextIOWrapper(z.open("Unihan_Variants.txt"), encoding="utf-8"):
        if line.startswith("U+") and "\tkSimplifiedVariant\t" in line:
            cp, _, value = line.rstrip("\n").split("\t")
            c = chr(int(cp[2:], 16))
            if c not in [chr(int(v[2:], 16)) for v in value.split()]:
                traditional.add(c)

header, words = [], []
for line in open(CJDICT, encoding="utf-8"):
    line = line.rstrip("\n").lstrip("﻿")
    if line.lstrip().startswith("#"):
        header.append("#" + line.lstrip()[1:])
        continue
    if not line.strip():
        continue
    word, _, cost = line.partition("\t")
    if len(word) > 1 and any(c in traditional for c in word):
        continue
    words.append(word + "\t" + (cost if cost.isdigit() else "255"))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/gen-smartcn-dict.py from ICU 74.2 cjdict.txt; its notices:\n")
    f.write("\n".join(header) + "\n")
    f.write("\n".join(words) + "\n")
