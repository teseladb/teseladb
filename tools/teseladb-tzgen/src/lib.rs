//! Generator of `teseladb-tz`'s data: from the IANA tzdata files that `scripts/fetch-pinned.sh
//! scripts/tzdata.sha256` downloads (2024a, the version the reference server 9.0.4's timelib
//! carries), it builds `main.zi` with the `backzone` history as the reference server's database has
//! it (`make PACKRATDATA=backzone PACKRATLIST=zone.tab main.zi`), compiles it with the system's
//! `zic -b fat`, reads every compiled TZif file and writes `crates/teseladb-tz/src/tzdata.rs`.
//! `--check` only compares with the file in the repository.
//!
//!   teseladb-tzgen "$(scripts/fetch-pinned.sh scripts/tzdata.sha256)/tzdata2024a.tar.gz"
#![cfg_attr(coverage, feature(coverage_attribute))]
#![forbid(unsafe_code)]

pub mod tzif;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::tzif::Tzif;

/// The generated file, under the repository.
pub const OUTPUT: &str = "crates/teseladb-tz/src/tzdata.rs";
/// Where `zic` writes, under the tzdata directory.
const ZONEINFO: &str = "zoneinfo-fat";

/// The message of an I/O error on `path`.
fn at(path: &Path) -> impl FnOnce(std::io::Error) -> String + '_ {
    move |e| format!("{}: {e}", path.display())
}

fn run_tool(dir: &Path, program: &str, args: &[&str]) -> Result<(), String> {
    let status = Command::new(program)
        .args(args)
        .current_dir(dir)
        .status()
        .map_err(at(Path::new(program)))?;
    if status.success() { Ok(()) } else { Err(format!("{program} {}: {status}", args.join(" "))) }
}

/// Every regular file under `dir`, with its path relative to the walk's start (`prefix` is the
/// part already walked).
fn files(dir: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) -> Result<(), String> {
    for entry in fs::read_dir(dir).map_err(at(dir))? {
        let path = entry.map_err(at(dir))?.path();
        let name = format!("{prefix}{}", path.file_name().unwrap_or_default().to_string_lossy());
        if path.is_dir() {
            files(&path, &format!("{name}/"), out)?;
        } else if path.is_file() {
            out.push((name, path));
        }
    }
    Ok(())
}

/// An integer literal as Clippy's `unreadable_literal` wants it: groups of three digits separated by
/// `_` from six digits on, so that the generated file passes the strict lints of the workspace.
#[must_use]
pub fn literal(v: i64) -> String {
    let digits = v.unsigned_abs().to_string();
    if digits.len() < 6 {
        return v.to_string();
    }
    let mut grouped = String::with_capacity(digits.len() + digits.len() / 3 + 1);
    for (i, d) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            grouped.push('_');
        }
        grouped.push(d);
    }
    if v < 0 { format!("-{grouped}") } else { grouped }
}

/// The Rust source of the database: `version` and every zone of `zones`.
pub fn render(version: &str, zones: &BTreeMap<String, Tzif>) -> String {
    let mut unique: Vec<&Tzif> = Vec::new();
    let mut names = Vec::new();
    for (name, z) in zones {
        let index = if let Some(i) = unique.iter().position(|u| *u == z) {
            i
        } else {
            unique.push(z);
            unique.len() - 1
        };
        names.push((name, index));
    }
    let mut out = String::new();
    out.push_str(
        "//! Generated by `teseladb-tzgen` from the IANA time zone database; do not edit.\n\n",
    );
    out.push_str("use crate::{LocalType, ZoneData};\n\n");
    out.push_str("/// The version of the IANA database.\n");
    let _ = write!(out, "pub const VERSION: &str = \"{version}\";\n\n");
    out.push_str("/// Every zone name, in order, with its data's index in [`ZONES`].\n");
    let _ = writeln!(out, "pub static NAMES: [(&str, u16); {}] = [", names.len());
    for (n, i) in &names {
        let _ = writeln!(out, "    (\"{n}\", {i}),");
    }
    out.push_str("];\n\n/// The data of each zone.\n");
    let _ = writeln!(out, "pub static ZONES: [ZoneData; {}] = [", unique.len());
    for z in &unique {
        out.push_str("    ZoneData {\n        transitions: &[");
        out.push_str(&z.transitions.iter().map(|&t| literal(t)).collect::<Vec<_>>().join(", "));
        out.push_str("],\n        indices: &[");
        out.push_str(&z.indices.iter().map(u8::to_string).collect::<Vec<_>>().join(", "));
        out.push_str("],\n        types: &[\n");
        for t in &z.types {
            let _ = writeln!(
                out,
                "            LocalType {{ offset: {}, dst: {}, abbr: \"{}\" }},",
                literal(i64::from(t.offset)),
                t.dst,
                t.abbr
            );
        }
        let _ = write!(out, "        ],\n        footer: \"{}\",\n    }},\n", z.footer);
    }
    out.push_str("];\n");
    out
}

/// The binary's work: runs the generator and writes its message to `out` (success) or `err`.
pub fn main(
    args: &[String],
    root: &Path,
    out: &mut dyn std::io::Write,
    err: &mut dyn std::io::Write,
) -> std::process::ExitCode {
    let (code, message) = run(args, root);
    // A message that cannot be written changes nothing in what was generated.
    let _ = if code == 0 { writeln!(out, "{message}") } else { writeln!(err, "{message}") };
    std::process::ExitCode::from(code)
}

/// Runs the generator: `args` are the tzdata directory and maybe `--check`; `root` is the
/// repository. Gives the exit code and the message.
#[must_use]
pub fn run(args: &[String], root: &Path) -> (u8, String) {
    match generate(args, root) {
        Ok(m) => (0, m),
        Err(e) => (1, e),
    }
}

fn generate(args: &[String], root: &Path) -> Result<String, String> {
    let check = args.iter().any(|a| a == "--check");
    let given = args
        .iter()
        .find(|a| *a != "--check")
        .map(PathBuf::from)
        .ok_or("usage: teseladb-tzgen <tzdata tarball or directory> [--check]")?;
    // A tarball (as scripts/fetch-pinned.sh leaves it) is unpacked beside itself.
    let dir = if given.is_file() {
        let dir = given.with_extension("d");
        fs::create_dir_all(&dir).map_err(at(&dir))?;
        let tarball = given.canonicalize().map_err(at(&given))?;
        run_tool(&dir, "tar", &["-xzf", &tarball.to_string_lossy()])?;
        dir
    } else {
        given
    };
    let version = fs::read_to_string(dir.join("version"))
        .map_err(at(&dir.join("version")))?
        .trim()
        .to_owned();
    run_tool(&dir, "make", &["PACKRATDATA=backzone", "PACKRATLIST=zone.tab", "main.zi"])?;
    run_tool(&dir, "zic", &["-b", "fat", "-d", ZONEINFO, "main.zi"])?;
    write_database(&dir.join(ZONEINFO), &version, root, check)
}

/// Reads every TZif file under `base` and writes (or, with `check`, compares) the database of
/// IANA version `version` under repository `root`.
///
/// # Errors
///
/// A message naming the file and the I/O error, a TZif file that does not parse, `rustfmt` failing, or,
/// with `check`, a database that differs from the file in the repository.
pub fn write_database(
    base: &Path,
    version: &str,
    root: &Path,
    check: bool,
) -> Result<String, String> {
    let mut found = Vec::new();
    files(base, "", &mut found)?;
    let mut zones = BTreeMap::new();
    for (name, path) in found {
        let bytes = fs::read(&path).map_err(at(&path))?;
        if let Some(z) = Tzif::parse(&bytes).map_err(|e| format!("{name}: {e}"))? {
            zones.insert(name, z);
        }
    }
    // The file is written as rustfmt leaves it, so that the formatting gate passes.
    let out = root.join(OUTPUT);
    let target = if check { out.with_extension("rs.check") } else { out.clone() };
    fs::write(&target, render(version, &zones)).map_err(at(&target))?;
    run_tool(root, "rustfmt", &["--edition", "2024", &target.to_string_lossy()])?;
    if check {
        let fresh = fs::read_to_string(&target).map_err(at(&target))?;
        fs::remove_file(&target).map_err(at(&target))?;
        let current = fs::read_to_string(&out).map_err(at(&out))?;
        if current != fresh {
            return Err(format!(
                "{OUTPUT} differs from the generator's output for tzdata {version}"
            ));
        }
        return Ok(format!("{OUTPUT} matches tzdata {version}"));
    }
    Ok(format!("wrote {OUTPUT}: {} zones, tzdata {version}", zones.len()))
}
